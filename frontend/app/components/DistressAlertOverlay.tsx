/**
 * Translates a static distress UI string key, supporting optional {var} substitutions.
 */
export function tDistress(
  lang: LangCode,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const row = DISTRESS_UI_STRINGS[key];
  let text = row?.[lang] ?? row?.en ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

/**
 * Resolves a normalized category key (e.g., 'sinking', 'medical', 'engine_failure', 'man_overboard', 'general').
 */
export function resolveDistressCategoryKey(
  categoryTitle?: string | null,
  categoryKey?: string | null,
  text?: string | null,
): string {
  if (categoryKey && categoryKey in PRESET_SURVIVAL_STEPS) {
    return categoryKey;
  }
  const combined = `${categoryTitle ?? ""} ${text ?? ""}`.toLowerCase();
  if (combined.includes("bleed") || combined.includes("injur") || combined.includes("medic") || combined.includes("heart") || combined.includes("doctor")) {
    return "medical";
  }
  if (combined.includes("sink") || combined.includes("water") || combined.includes("capsiz") || combined.includes("doob") || combined.includes("mung")) {
    return "sinking";
  }
  if (combined.includes("overboard") || combined.includes("mob") || combined.includes("drown") || combined.includes("fell in")) {
    return "man_overboard";
  }
  if (combined.includes("engine") || combined.includes("motor") || combined.includes("adrift") || combined.includes("fuel") || combined.includes("propeller")) {
    return "engine_failure";
  }
  return "general";
}

/**
 * Translates a survival category name into the target language.
 */
export function translateSurvivalCategory(
  categoryKey: string,
  categoryTitle: string | undefined,
  lang: LangCode,
): string {
  const cat = SURVIVAL_CATEGORIES[categoryKey] ?? SURVIVAL_CATEGORIES.default;
  return cat[lang] ?? cat.en ?? categoryTitle ?? "Emergency Maritime Survival Actions";
}

/**
 * Translates an authority name (e.g. "Indian Coast Guard MRCC", "Colachel Coastal Authority", "Mumbai Port Authority").
 */
export function translateAuthorityName(authName: string | undefined, lang: LangCode): string {
  if (!authName) return tDistress(lang, "coastal_authority_suffix");

  if (authName.toLowerCase().includes("indian coast guard") || authName.toLowerCase().includes("mrcc")) {
    return tDistress(lang, "mrcc_default_name");
  }

  // Check if authority begins with a known port name, e.g. "Colachel Coastal Authority"
  const suffix = tDistress(lang, "coastal_authority_suffix");
  const words = authName.split(" ");
  const candidatePort = words[0];
  const translatedPort = translatePortName(candidatePort, lang);
  if (translatedPort && translatedPort !== candidatePort) {
    return `${translatedPort} ${suffix}`;
  }

  return authName;
}

/**
 * Translates the emergency unit title (e.g. "Port Control & Marine Police").
 */
export function translateEmergencyUnit(unit: string | undefined, lang: LangCode): string {
  if (!unit) return tDistress(lang, "default_port_unit");
  if (unit.toLowerCase().includes("port control") || unit.toLowerCase().includes("marine police")) {
    return tDistress(lang, "default_port_unit");
  }
  return unit;
}

/**
 * Translates a survival step into the user's preferred language.
 */
export function translateSurvivalStep(
  rawStep: string,
  index: number,
  categoryKey: string,
  lang: LangCode,
): SurvivalStepItem {
  if (lang === "en") {
    const colonIdx = rawStep.indexOf(":");
    return {
      title: colonIdx !== -1 ? rawStep.slice(0, colonIdx).trim() : `ACTION STEP ${index + 1}`,
      details: colonIdx !== -1 ? rawStep.slice(colonIdx + 1).trim() : rawStep.trim(),
    };
  }

  // 1. Try matching with category's preset indexed step
  const presetList = PRESET_SURVIVAL_STEPS[categoryKey];
  if (presetList && index < presetList.length) {
    const item = presetList[index][lang];
    if (item) return item;
  }

  // 2. Try keyword matching across all preset steps in all categories
  const rawLower = rawStep.toLowerCase();
  for (const catSteps of Object.values(PRESET_SURVIVAL_STEPS)) {
    for (const stepMap of catSteps) {
      const enItem = stepMap.en;
      if (
        enItem &&
        (rawLower.includes(enItem.title.toLowerCase().slice(0, 10)) ||
          rawLower.includes(enItem.details.toLowerCase().slice(0, 18)))
      ) {
        return stepMap[lang] ?? stepMap.en;
      }
    }
  }

  // 3. Fallback: split by colon and translate header label
  const colonIdx = rawStep.indexOf(":");
  const fallbackTitle = colonIdx !== -1 ? rawStep.slice(0, colonIdx).trim() : tDistress(lang, "action_step", { step: index + 1 });
  const fallbackDetails = colonIdx !== -1 ? rawStep.slice(colonIdx + 1).trim() : rawStep.trim();

  return {
    title: fallbackTitle,
    details: fallbackDetails,
  };
}

