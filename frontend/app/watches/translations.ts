export function translatePortLocation(lang: LangCode, portName: string): string {
  if (lang === "en" || !portName) return portName;
  const direct = PORT_TRANSLATIONS[portName]?.[lang];
  if (direct) return direct;
  // Try matching port names like "Beypore Port" -> "Beypore"
  const clean = portName.replace(/\s+Port$/i, "").trim();
  const ports = PORT_TRANSLATIONS as Record<string, Partial<Record<LangCode, string>>>;
  for (const [k, val] of Object.entries(ports)) {
    if (k.toLowerCase() === clean.toLowerCase() && val?.[lang]) {
      const portSuffix = {
        kn: " ಬಂದರು",
        ta: " துறைமுகம்",
        hi: " बंदरगाह",
        te: " నౌకాశ్రయం",
        ml: " തുറമുഖം",
        mr: " बंदर",
        bn: " বন্দর",
        gu: " પોર્ટ",
        or: " ବନ୍ଦର",
      }[lang] || " Port";
      return `${val[lang]}${portSuffix}`;
    }
  }
  return portName;
}

