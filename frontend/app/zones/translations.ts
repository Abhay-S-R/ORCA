// ─── 5. EXPORTED HOOK & HELPERS ───────────────────────────────────────────────

export function translateZoneUi(lang: LangCode, key: string): string {
  if (lang === "en") return key;
  return UI_STRINGS[key]?.[lang] ?? key;
}

export function translateZoneName(lang: LangCode, name: string): string {
  if (lang === "en" || !name) return name;
  return ZONE_TRANSLATIONS[name]?.name[lang] ?? name;
}

export function translateZoneDescription(lang: LangCode, desc: string, zoneName?: string): string {
  if (lang === "en" || !desc) return desc;
  if (zoneName && ZONE_TRANSLATIONS[zoneName]?.desc[lang]) {
    return ZONE_TRANSLATIONS[zoneName].desc[lang]!;
  }
  for (const [key, item] of Object.entries(ZONE_TRANSLATIONS)) {
    if (item.desc[lang] && (desc.toLowerCase().includes(key.toLowerCase()))) {
      return item.desc[lang]!;
    }
  }
  return desc;
}

export function translateSpecies(lang: LangCode, name: string): string {
  if (lang === "en" || !name) return name;
  return SPECIES_TRANSLATIONS[name]?.[lang] ?? name;
}

export function translateBearing(lang: LangCode, compass: string): string {
  if (lang === "en" || !compass) return compass;
  return COMPASS_NAMES[compass.trim().toUpperCase()]?.[lang] ?? compass;
}

export function useZonesT() {
  const { language } = useLanguage();

  return {
    language,
    t: (key: string): string => translateZoneUi(language, key),
    zoneName: (name: string): string => translateZoneName(language, name),
    zoneDesc: (desc: string, name?: string): string => translateZoneDescription(language, desc, name),
    species: (name: string): string => translateSpecies(language, name),
    bearing: (comp: string): string => translateBearing(language, comp),
  };
}

