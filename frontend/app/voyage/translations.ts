export function translateVoyageUi(lang: LangCode, key: string): string {
  if (!key) return key;
  if (key === "voyage.lede") {
    key = LEDE_TEXT;
  }
  if (lang === "en") return key;
  return UI_STRINGS[key]?.[lang] ?? key;
}

export function useVoyageT() {
  const { language } = useLanguage();

  return {
    language,
    t: (key: string): string => translateVoyageUi(language, key),
  };
}
