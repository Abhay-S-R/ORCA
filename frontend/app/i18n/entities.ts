export function translateStateName(state: string | null | undefined, lang: string | null | undefined): string {
  if (!state) return "";
  if (!lang || lang === "en") return state;
  const l = lang as LangCode;
  const direct = STATE_TRANSLATIONS[state]?.[l];
  if (direct) return direct;
  const lower = state.trim().toLowerCase();
  for (const [key, val] of Object.entries(STATE_TRANSLATIONS)) {
    if (key.toLowerCase() === lower && val[l]) return val[l]!;
  }
  for (const [key, val] of Object.entries(STATE_TRANSLATIONS)) {
    if (lower.includes(key.toLowerCase()) && val[l]) return val[l]!;
  }
  return state;
}

