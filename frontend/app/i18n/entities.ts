export function translatePortName(name: string | null | undefined, lang: string | null | undefined): string {
  if (!name) return "";
  if (!lang || lang === "en") return name;
  const l = lang as LangCode;
  const trimmed = name.trim();
  const direct = PORT_TRANSLATIONS[name]?.[l] ?? PORT_TRANSLATIONS[trimmed]?.[l];
  if (direct) return direct;
  // Also strip " Port", " Harbour", " Harbor" if appended
  const baseName = trimmed.replace(/\s+(Port|Harbour|Harbor|Dock|Jetty|Terminal)$/i, "").trim();
  const baseDirect = PORT_TRANSLATIONS[baseName]?.[l];
  if (baseDirect) return baseDirect;
  return name;
}

